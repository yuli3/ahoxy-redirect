#!/usr/bin/env node
// ahoxy-legacy next.config.mjs 매핑(redirects-source.json, 423룰) →
// Cloudflare Pages public/_redirects 변환기.
//
// Cloudflare Pages 한도: static 2,000 / dynamic(placeholder·splat) 100.
// 그래서 :locale 플레이스홀더는 실제 로케일(ko/en/ja/es)로 정적 전개하고,
// `/:path*` 접미 변형은 같은 목적지의 splat 1줄로 합친다. splat(동적) 수를
// 카운트해 100 초과 시 빌드 실패시킨다 (조용한 드롭 방지 — 과거 사고 재발 금지).
import { readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const LOCALES = ["ko", "en", "ja", "es"]; // ahoxy-legacy src/i18n/config.ts
const rules = JSON.parse(readFileSync(join(__dirname, "redirects-source.json"), "utf8"));

// 전략: splat(동적)은 한도 100이라 사용 불가(444개 필요했음). 대신
//  - 정확 매치(+트레일링 슬래시)는 정적 룰로 엣지 301
//  - 서브경로(/foo/anything)는 404.astro 스텁이 레포 내 redirect-map.json으로
//    최장 프리픽스 매치 → 0초 meta refresh (blog OiyoCanonicalRedirect 패턴)
const staticLines = new Map(); // source -> line (dedupe, first-wins = legacy order)
const dynLines = new Map(); // named placeholder rules only (few)
const prefixMap = new Map(); // 404 스텁용: pathPrefix -> destination

function addStatic(src, dest) {
  // 트레일링 슬래시 변형은 별도 룰로 만들지 않는다 — Cloudflare 정규화 + 404 스텁이 커버 (2,000 한도 절약)
  if (!staticLines.has(src)) staticLines.set(src, `${src} ${dest} 301`);
}

// pass 1 — 변형 전개 (아직 상대 목적지 허용). exactMap은 체인 해소용.
const expanded = []; // { s, d, kind: 'static'|'splat'|'dyn' }
const exactMap = new Map(); // 정확 source → dest (첫 룰 우선)

for (const r of rules) {
  // Next.js 전용 has 조건(쿼리 매치)은 Cloudflare로 번역 불가 — 스킵 (감사 이슈 #1)
  if (r.has) {
    console.warn("skip has-condition rule:", r.source);
    continue;
  }
  // `:locale(en|ko|...)` regex 제약 → 제약 안의 로케일 목록으로 전개 (감사 이슈 #3: 로케일 루트 커버)
  let src = r.source;
  let ruleLocales = LOCALES;
  const con = src.match(/:locale\(([^)]+)\)/);
  if (con) {
    ruleLocales = con[1].split("|");
    src = src.replace(/:locale\([^)]+\)/, ":locale");
  }
  const dest = r.destination.replaceAll(":locale", ":l"); // temp marker

  const variants = src.includes(":locale")
    ? ruleLocales.map((l) => ({ s: src.replaceAll(":locale", l), d: dest.replaceAll(":l", l) }))
    : [{ s: src, d: dest.replaceAll(":l", "ko") }];

  for (const { s, d } of variants) {
    if (/:\w+\*/.test(s)) {
      const prefix = s.replace(/\/:\w+\*$/, "");
      const target = d.replace(/[/]?:\w+\*/g, "");
      expanded.push({ s: prefix, d: target, kind: "splat" });
      if (!exactMap.has(prefix)) exactMap.set(prefix, target);
    } else if (s.includes(":")) {
      expanded.push({ s, d, kind: "dyn" });
    } else {
      expanded.push({ s, d, kind: "static" });
      if (!exactMap.has(s)) exactMap.set(s, d);
    }
  }
}

// pass 2 — 상대(내부) 목적지 체인 해소 (감사 이슈 #2: 데드엔드 체인 54개).
// 쉘에는 내부 콘텐츠가 없으므로 외부 URL까지 따라가고, 못 풀면 드롭(404 스텁이 로케일 루트로 처리).
function resolveExternal(dest) {
  let d = dest;
  for (let hop = 0; hop < 6 && d.startsWith("/"); hop++) {
    const next = exactMap.get(d.split("?")[0]);
    if (!next) return null;
    d = next;
  }
  return d.startsWith("/") ? null : d;
}

let dropped = 0;
for (const { s, d, kind } of expanded) {
  const finalDest = d.startsWith("/") ? resolveExternal(d) : d;
  if (!finalDest) {
    dropped++;
    continue;
  }
  if (kind === "dyn") {
    if (!dynLines.has(s)) dynLines.set(s, `${s} ${finalDest} 301`);
  } else {
    addStatic(s, finalDest);
    if (!prefixMap.has(s)) prefixMap.set(s, finalDest);
  }
}
if (dropped) console.warn(`dropped ${dropped} unresolvable internal-chain rules (404 stub will catch)`);

addStatic("/", "https://oiyo.net/ko/?utm_source=ahoxy&utm_medium=redirect&utm_campaign=root");
// mbti/results(has-룰 대체): 결과 딥링크는 oiyo mbti 테스트로
for (const l of LOCALES) {
  addStatic(`/${l}/mbti/results`, `https://oiyo.net/${l}/mbti/test?utm_source=ahoxy&utm_medium=redirect&utm_campaign=mbti-results`);
  if (!prefixMap.has(`/${l}/mbti/results`)) prefixMap.set(`/${l}/mbti/results`, `https://oiyo.net/${l}/mbti/test?utm_source=ahoxy&utm_medium=redirect&utm_campaign=mbti-results`);
}

const lines = [
  "# ahoxy.com → oiyo family 전면 이전 (2026-07-03). generated by scripts/generate-redirects.mjs",
  "# 정확매치=엣지 301 · 서브경로=404 스텁(redirect-map.json 프리픽스 매치)",
  ...staticLines.values(),
  ...dynLines.values(),
];

if (dynLines.size > 100) {
  console.error(`FATAL: dynamic rules ${dynLines.size} > 100 (Cloudflare limit) — rules would be silently dropped`);
  process.exit(1);
}
if (staticLines.size > 2000) {
  console.error(`FATAL: static rules ${staticLines.size} > 2000 (Cloudflare limit)`);
  process.exit(1);
}

writeFileSync(join(__dirname, "..", "public", "_redirects"), lines.join("\n") + "\n");
writeFileSync(
  join(__dirname, "..", "src", "redirect-map.json"),
  JSON.stringify(Object.fromEntries([...prefixMap.entries()].sort((a, b) => b[0].length - a[0].length)), null, 1),
);
console.log(`_redirects: static=${staticLines.size} dynamic=${dynLines.size} · redirect-map.json prefixes=${prefixMap.size}`);
