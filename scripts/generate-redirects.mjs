#!/usr/bin/env node
// ahoxy-legacy next.config.mjs 매핑(redirects-source.json, 423룰) →
// Cloudflare Pages public/_redirects 변환기.
//
// Cloudflare Pages 한도: static 2,000 / dynamic(placeholder·splat) 100.
// 그래서 :locale 플레이스홀더는 실제 로케일(ko/en/ja/es)로 정적 전개하고,
// `/:path*` 접미 변형은 같은 목적지의 splat 1줄로 합친다. splat(동적) 수를
// 카운트해 100 초과 시 빌드 실패시킨다 (조용한 드롭 방지 — 과거 사고 재발 금지).
import { readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const LOCALES = ["ko", "en", "ja", "es"]; // ahoxy-legacy src/i18n/config.ts
const rules = JSON.parse(readFileSync(join(__dirname, "redirects-source.json"), "utf8"));

// 전략: splat(동적)은 한도 100이라 사용 불가(444개 필요했음). 대신
//  - 정확 매치(+트레일링 슬래시)는 정적 룰로 엣지 301
//  - 서브경로(/foo/anything)는 404.astro 스텁이 레포 내 redirect-map.json으로
//    최장 프리픽스 매치 → 0초 meta refresh (blog OiyoCanonicalRedirect 패턴)
const staticLines = new Map(); // source -> line (dedupe, first-wins = legacy order)
const dynLines = new Map(); // named placeholder rules only (few)
const prefixMap = new Map(); // 404 스텁용: pathPrefix -> destination

function addStatic(src, dest) {
  // 트레일링 슬래시 변형은 별도 룰로 만들지 않는다 — Cloudflare 정규화 + 404 스텁이 커버 (2,000 한도 절약)
  if (!staticLines.has(src)) staticLines.set(src, `${src} ${dest} 301`);
}

for (const r of rules) {
  const dest = r.destination.replaceAll(":locale", ":l"); // temp marker
  const src = r.source;

  const variants = src.includes(":locale")
    ? LOCALES.map((l) => ({ s: src.replaceAll(":locale", l), d: dest.replaceAll(":l", l) }))
    : [{ s: src, d: dest.replaceAll(":l", "ko") }];

  for (const { s, d } of variants) {
    if (/:\w+\*/.test(s)) {
      const prefix = s.replace(/\/:\w+\*$/, "");
      const target = d.replace(/[/]?:\w+\*/g, "");
      if (!prefixMap.has(prefix)) prefixMap.set(prefix, target);
      addStatic(prefix, target); // 정확 매치도 커버
    } else if (s.includes(":")) {
      // named placeholder (e.g. /ko/year/:year) — Cloudflare dynamic rule (한도 100, 소수만)
      if (!dynLines.has(s)) dynLines.set(s, `${s} ${d} 301`);
    } else {
      addStatic(s, d);
      if (!prefixMap.has(s)) prefixMap.set(s, d); // 서브경로 스텁 매칭에도 등록
    }
  }
}

addStatic("/", "https://oiyo.net/ko/?utm_source=ahoxy&utm_medium=redirect&utm_campaign=root");

const lines = [
  "# ahoxy.com → oiyo family 전면 이전 (2026-07-03). generated by scripts/generate-redirects.mjs",
  "# 정확매치=엣지 301 · 서브경로=404 스텁(redirect-map.json 프리픽스 매치)",
  ...staticLines.values(),
  ...dynLines.values(),
];

if (dynLines.size > 100) {
  console.error(`FATAL: dynamic rules ${dynLines.size} > 100 (Cloudflare limit) — rules would be silently dropped`);
  process.exit(1);
}
if (staticLines.size > 2000) {
  console.error(`FATAL: static rules ${staticLines.size} > 2000 (Cloudflare limit)`);
  process.exit(1);
}

writeFileSync(join(__dirname, "..", "public", "_redirects"), lines.join("\n") + "\n");
writeFileSync(
  join(__dirname, "..", "src", "redirect-map.json"),
  JSON.stringify(Object.fromEntries([...prefixMap.entries()].sort((a, b) => b[0].length - a[0].length)), null, 1),
);
console.log(`_redirects: static=${staticLines.size} dynamic=${dynLines.size} · redirect-map.json prefixes=${prefixMap.size}`);
